// Ergonomic, RAII C++ API over the generated `ffi/tokenizer_shim.h` C header
// (itself generated by cbindgen from the real Rust shim in `rust/src/lib.rs`
// -- never hand-written, so it can't drift from the real FFI signatures).
// Callers should use this header, not the raw `extern "C"` functions in
// `ffi/tokenizer_shim.h` directly.
//
// Scope: this binds exactly what `SingleTurnAgentLoop.run()` exercises for
// the validated Qwen3-4B / GSM8K single-turn, text-only workload --
// `ContinuousTokenBuilder.build_initial_tokens` (the only method that
// actually touches a tokenizer) plus pure-C++ ports of
// `merge_assistant_tokens` / `align_response_metadata` (which touch no
// tokenizer at all -- confirmed by reading
// `verl/utils/tokenizer/continuous_token.py`). See README.md for the full
// scoping trace, the chat-template-parity finding, and what was/wasn't
// verified.

#pragma once

#include <cstdint>
#include <memory>
#include <optional>
#include <string>
#include <vector>

namespace verl_continuous_token {

// Thrown on any failure from the Rust shim (tokenizer load failure, template
// parse/render failure, or a malformed `messages` structure). `what()` is the
// real error message produced by the Rust side (`tokenizers`/`minijinja`
// error `Display` output), not a generic wrapper message.
class ContinuousTokenError : public std::exception {
 public:
  explicit ContinuousTokenError(std::string message) : message_(std::move(message)) {}
  const char* what() const noexcept override { return message_.c_str(); }

 private:
  std::string message_;
};

// A single chat message. Only `role` + `content` are modeled: that is the
// only shape `build_initial_tokens` actually receives on the validated
// single-turn GSM8K path (no `tool_calls`/`reasoning_content`, since those
// only ever appear on assistant messages, and assistant messages are never
// part of the *initial* prompt rendered by `build_initial_tokens`). Porting
// the richer message shape (tool calls, reasoning content, multimodal
// content parts) is explicitly out of scope -- see README.md.
struct ChatMessage {
  std::string role;     // e.g. "system", "user"
  std::string content;
};

// Port of verl's `ContinuousTokenBuilder` (base class) for the single-turn,
// text-only, no-tools path. `QwenContinuousTokenBuilder` does NOT override
// `build_initial_tokens`, `merge_assistant_tokens`, or
// `align_response_metadata` -- only `_merge_context_token_ids` (used by
// `merge_context_tokens`, which `SingleTurnAgentLoop` never calls) -- so for
// this exact workload, the base class's behavior *is* the Qwen behavior.
// See README.md's scoping trace for how this was confirmed by reading the
// real call path, not assumed.
class ContinuousTokenBuilder {
 public:
  // `tokenizer_json_path`: path to the HF-standard `tokenizer.json` (the
  // same file the Qwen3 checkpoint already ships).
  // `chat_template`: the raw Jinja2 template string, verbatim from the
  // checkpoint's `tokenizer_config.json`'s `"chat_template"` field. Callers
  // own reading that file; this class does not parse `tokenizer_config.json`
  // itself (one string field does not justify a second JSON-schema
  // dependency here).
  //
  // Throws `ContinuousTokenError` if the tokenizer fails to load or the
  // template fails to parse.
  ContinuousTokenBuilder(const std::string& tokenizer_json_path, const std::string& chat_template);

  ~ContinuousTokenBuilder();
  ContinuousTokenBuilder(const ContinuousTokenBuilder&) = delete;
  ContinuousTokenBuilder& operator=(const ContinuousTokenBuilder&) = delete;
  ContinuousTokenBuilder(ContinuousTokenBuilder&&) noexcept;
  ContinuousTokenBuilder& operator=(ContinuousTokenBuilder&&) noexcept;

  // Port of `ContinuousTokenBuilder.build_initial_tokens` ->
  // `ContinuousTokenBuilder._render_tokens` ->
  // `verl.utils.tokenizer.chat_template.apply_chat_template` (the
  // `tools=None` branch -- `SingleTurnAgentLoop` never passes `tools` to
  // `ct_build_initial_tokens`, so the `try` branch of that function's
  // `apply_chat_template` is what's ported; the `except` fallback for
  // Qwen3.5-style "needs at least one user message" templates is not
  // exercised by Qwen3 and is out of scope here).
  //
  // `enable_thinking`: `std::nullopt` means the kwarg is genuinely absent
  // from `chat_template_kwargs` (the GSM8K default) -- NOT the same thing to
  // the Jinja template as an explicit `false`, since it checks
  // `enable_thinking is defined`.
  //
  // Throws `ContinuousTokenError` on render/tokenize failure.
  std::vector<int64_t> build_initial_tokens(const std::vector<ChatMessage>& messages,
                                             bool add_generation_prompt = true,
                                             std::optional<bool> enable_thinking = std::nullopt) const;

 private:
  struct Impl;
  std::unique_ptr<Impl> impl_;
};

// Mirrors Python's `MergeResult` dataclass
// (`verl/utils/tokenizer/continuous_token.py`). Pure data, no tokenizer
// involvement -- see `merge_assistant_tokens`/`align_response_metadata`
// below.
struct MergeResult {
  std::vector<int64_t> token_ids;
  int64_t appended_token_count = 0;
  std::string kind = "assistant";  // "assistant" | "context"; only
                                    // "assistant" is reachable for this
                                    // workload (SingleTurnAgentLoop never
                                    // calls ct_merge_context_msg) -- see
                                    // README.md.
  std::vector<int64_t> inserted_token_ids;
  int64_t removed_prefix_token_count = 0;
};

// Direct C++ port of `ContinuousTokenBuilder.merge_assistant_tokens`
// (base class; NOT overridden by `QwenContinuousTokenBuilder`). Pure
// list/int bookkeeping -- confirmed by reading the Python source, this
// touches no tokenizer state at all, so it does not call into the Rust
// shim. Python:
//
//   def merge_assistant_tokens(self, runtime_token_ids, assistant_token_ids):
//       merged_token_ids = list(runtime_token_ids) + list(assistant_token_ids)
//       return MergeResult(token_ids=merged_token_ids,
//                           appended_token_count=len(assistant_token_ids),
//                           kind="assistant")
MergeResult merge_assistant_tokens(const std::vector<int64_t>& runtime_token_ids,
                                   const std::vector<int64_t>& assistant_token_ids);

// Mirrors the `(aligned_mask, aligned_logprobs)` tuple
// `align_response_metadata` returns in Python.
struct AlignedResponseMetadata {
  std::vector<int64_t> response_mask;
  std::optional<std::vector<double>> response_logprobs;
};

// Direct C++ port of `ContinuousTokenBuilder.align_response_metadata` (base
// class; NOT overridden by `QwenContinuousTokenBuilder`). Pure list/int
// bookkeeping, same as `merge_assistant_tokens` above -- no tokenizer
// involvement.
//
// Throws `std::invalid_argument` matching the Python source's `ValueError`s
// (e.g. `assistant_logprobs` required when `response_logprobs` is given but
// `assistant_logprobs` is not, for a non-empty assistant append; length
// mismatch between `assistant_logprobs` and `merge_result.appended_token_count`).
AlignedResponseMetadata align_response_metadata(
    const MergeResult& merge_result, const std::vector<int64_t>& response_mask,
    const std::optional<std::vector<double>>& response_logprobs,
    const std::optional<std::vector<double>>& assistant_logprobs = std::nullopt);

}  // namespace verl_continuous_token
